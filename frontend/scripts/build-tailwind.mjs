import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile, optimize } from "@tailwindcss/node";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectDir = path.resolve(scriptDir, "..");
const srcDir = path.join(projectDir, "src");
const inputCssPath = path.join(srcDir, "index.css");
const outputCssPath = path.join(srcDir, "generated.css");
const contentExtensions = new Set([".ts", ".tsx", ".html"]);

const walk = async (directory) => {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const resolvedPath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        return walk(resolvedPath);
      }

      return contentExtensions.has(path.extname(entry.name)) ? [resolvedPath] : [];
    })
  );

  return files.flat();
};

const extractCandidates = (source) => {
  const candidates = new Set();
  const literalPattern = /["'`]([^"'`]+)["'`]/g;

  for (const match of source.matchAll(literalPattern)) {
    const literal = match[1];
    if (!literal) {
      continue;
    }

    for (const token of literal.split(/\s+/)) {
      const candidate = token.trim();
      if (!candidate || candidate.length > 160) {
        continue;
      }

      if (!/[A-Za-z]/.test(candidate)) {
        continue;
      }

      candidates.add(candidate);
    }
  }

  return candidates;
};

const buildStyles = async () => {
  const [inputCss, contentFiles] = await Promise.all([
    fs.readFile(inputCssPath, "utf8"),
    walk(srcDir)
  ]);

  const candidateSets = await Promise.all(
    contentFiles.map(async (filePath) => extractCandidates(await fs.readFile(filePath, "utf8")))
  );

  const candidates = new Set();
  for (const candidateSet of candidateSets) {
    for (const candidate of candidateSet) {
      candidates.add(candidate);
    }
  }

  const compiler = await compile(inputCss, {
    base: projectDir,
    from: inputCssPath,
    onDependency: () => {}
  });

  const compiledCss = compiler.build([...candidates]);
  const optimizedCss = optimize(compiledCss, {
    file: outputCssPath,
    minify: false
  }).code;

  const output = `/* This file is generated by scripts/build-tailwind.mjs. */\n${optimizedCss}`;
  await fs.writeFile(outputCssPath, output, "utf8");
};

await buildStyles();
